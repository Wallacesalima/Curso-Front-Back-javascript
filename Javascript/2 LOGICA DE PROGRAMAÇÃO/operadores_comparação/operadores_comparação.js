const a = 10;
const b = "10";

console.log(a == b);  // true  (compara apenas valores)
console.log(a === b); // false (compara valor e tipo)
console.log(a != b);  // false (valores são iguais)
console.log(a !== b); // true  (tipos são diferentes)
console.log(a > 5);   // true  (10 é maior que 5)
console.log(a < 5);   // false (10 não é menor que 5)
